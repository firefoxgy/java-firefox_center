package com.firefox.center.common.constants;

/**
 * Description: 正则表达式验证规则
 *
 * @author sujie
 * @since JDK 1.8
 * date: 2020/7/13 15:24
 */
public interface RegCheckConstants {

    /**
     * 日期格式 YYYY-MM-dd
     */
     String DATE_REG = "(^[\\d]{4}-(((0[13578]|1[02])-((0[1-9])|([12][0-9])|(3[01])))|(((0[469])|11)-((0[1-9])|([12][0-9])|30))|"
            + "(02-((0[1-9])|(1[0-9])|(2[0-8]))))$)|(^(((([02468][048])|([13579][26]))00)|([0-9]{2}(([02468][048])|([13579][26]))))-(((0[13578]|1[02])-"
            + "((0[1-9])|([12][0-9])|(3[01])))|(((0[469])|11)-((0[1-9])|([12][0-9])|30))|(02-((0[1-9])|(1[0-9])|(2[0-9]))))$)";

    /**
     * 1.密码必须由字母、数字组成，区分大小写
     * 2.密码长度为8-18位
     */
    String PASSWORD_REG ="^(?=.*[a-zA-Z])(?=.*[0-9])[A-Za-z0-9]{8,18}$";

    /**
     * 手机号码验证正则表达式
     */
    String TEL_REG ="^1([38][0-9]|4[579]|5[^4]|6[6]|7[0135678]|9[89])\\d{8}$";

}
